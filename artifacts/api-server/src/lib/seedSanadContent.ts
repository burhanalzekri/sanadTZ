export async function seedSanadContent(): Promise<void> {
  for (const pathway of pathways) {
    await db
      .insert(pathwaysTable)
      .values(pathway)
      .onConflictDoNothing({ target: pathwaysTable.slug });
  }

  for (const resource of resources) {
    await db
      .insert(contentItemsTable)
      .values(resource)
      .onConflictDoNothing({ target: contentItemsTable.seedKey });
  }
}
